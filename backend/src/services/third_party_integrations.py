async def send_slack_webhook(
    webhook_url: str,
    query: str,
    summary: str,
    citations_count: int = 0,
    channel_name: str = "#research-reports",
) -> Dict[str, Any]:
    """Push formatted research summary to a Slack channel via Incoming Webhook."""
    if not webhook_url:
        return {"success": False, "error": "Slack Webhook URL is not configured"}

    clean_summary = summary[:500] + "..." if len(summary) > 500 else summary

    payload = {
        "text": f"🧠 *New AI Research Report*: {query}",
        "blocks": [
            {
                "type": "header",
                "text": {
                    "type": "plain_text",
                    "text": "📊 TriVisionX AI Research Summary",
                    "emoji": True,
                },
            },
            {
                "type": "section",
                "fields": [
                    {"type": "mrkdwn", "text": f"*Topic / Query:*\n{query}"},
                    {"type": "mrkdwn", "text": f"*Citations Found:*\n{citations_count} sources"},
                ],
            },
            {"type": "divider"},
            {
                "type": "section",
                "text": {
                    "type": "mrkdwn",
                    "text": f"*Executive Summary:*\n>{clean_summary}",
                },
            },
            {
                "type": "context",
                "elements": [
                    {
                        "type": "mrkdwn",
                        "text": "⚡ *Generated by TriVisionX AI Agent* • Confidential",
                    }
                ],
            },
        ],
    }

    async with httpx.AsyncClient(timeout=10.0) as client:
        res = await client.post(webhook_url, json=payload)
        if res.status_code == 200:
            return {"success": True, "message": "Successfully posted to Slack!"}
        return {"success": False, "error": f"Slack API Error ({res.status_code}): {res.text}"}


